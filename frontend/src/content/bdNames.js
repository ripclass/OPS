// Bangladeshi name data for the demo persona generator.
//
// Generated from a compiled research dataset (Census 2022 community shares,
// national name-frequency data, and cohort samples drawn from public rolls).
// Trimmed to the fields the generator reads: name, tier, cohort, required
// completion, romanization variants. The reasoning behind every rule below
// lives with the research, not here; the short version is in the comments.
//
// Field keys are short because this ships to the browser:
//   n   name
//   t   tier: very_common | common | occasional
//   c   cohorts the name belongs to: older | mid | young
//       older = born ~1955-1975, mid = born ~1980-1995, young = born ~2000-2008
//   req the completions a given name REQUIRES (see -ul / -ur rule below)
//   solo self-contained: -uzzaman / -uddin / -ullah need no completion
//   v   romanization variants, sampled so a crowd is not spelled identically
//   pos where a female element may sit: terminal | middle | terminal_or_middle
//
// THE RULES THAT MATTER, in the order a Bangladeshi reader would notice them
// being broken:
//
// 1. -ul given names REQUIRE Islam / Alam / Haque / Hasan. -ur given names
//    REQUIRE Rahman. A bare "Mizanur", or a "Mizanur Islam", is the sharpest
//    single tell of a generated name.
// 2. Hindu women carry a MEDIAL gendered element before an inherited surname
//    (Shefali Rani Das). Muslim women carry a TERMINAL one with nothing behind
//    it (Rahima Begum) and mostly have no inherited surname at all. Swapping
//    those positions is the most-botched structure in name generators.
// 3. Begum is a class marker, not the default. It is roughly 3 percent of women
//    nationally and zero among urban professionals. Akter carries the volume.
// 4. Md. / Mst. are honorifics, never given names, and never applied to Hindu,
//    Buddhist, Christian or indigenous people.
// 5. Poetic Bengali names (Bristi, Srabon, Nodi) live in the daak-nam slot.
//    "Bristi Islam" on a document does not happen.
// 6. Miah encodes rural and older. It is not a Sylhet marker.

